create policy "client_messages_client_insert_self"
  on public.client_messages for insert
  to authenticated
  with check (user_id = (select auth.uid()) and lower(client_email) = lower(coalesce((auth.jwt() ->> 'email'), '')) and direction = 'client_to_admin');

